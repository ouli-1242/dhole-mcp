"""W6 · degrade-no-silently: install hints come from a single helper.

The plan's core requirement (§3 W6.2 + W6 验收):

- ``grep 'pip install dhole-mcp[all]' src/dhole_mcp/server.py`` -> 0 (all
  occurrences go through ``install.full_install_command()``).
- A missing-tier response is *produced at the use point* (not at startup),
  and the copy is generated by the helper - so W7's extras flip lands in
  ``install.py`` alone, not across 49 sites.
- Tests that assert on the hint string (``test_bug_report_regressions.py``
  line 95 checks ``"dhole-mcp[all]" in r.error``) remain valid; do not
  change them here, and do not change them in W7 either unless W7's
  semantics force a rewrite.
"""

from __future__ import annotations

import re
from pathlib import Path

import pytest

from dhole_mcp import install


_SRC = Path(install.__file__).parent


def test_server_py_has_no_hardcoded_pip_install_all_literal():
    """The plan's grep-style test, spelled as a source-level assertion.

    Only install.py itself is allowed to contain the string; every other
    file in src/ must route through ``install.full_install_command()`` (or
    one of its tier-specific wrappers). A new occurrence in server.py means
    someone wrote a bare literal again and W7's one-line change will miss
    them.
    """
    server = (_SRC / "server.py").read_text(encoding="utf-8")
    hits = re.findall(r"pip install dhole-mcp\[all\]", server)
    assert not hits, f"server.py must not hard-code the install string; found {len(hits)}"


def test_install_helper_returns_the_current_string():
    """The string itself is still ``pip install dhole-mcp[all]`` today; W7
    flips the extras and this becomes ``pip install dhole-mcp`` with the
    ``[all]`` alias retained. Sites do not care which - they call this.
    """
    assert install.full_install_command() == "pip install dhole-mcp[all]"


class TestUsePointHintsAreHelperProduced:
    """The 3 tier sites the plan lists: browser missing / OCR missing /
    docx missing. Each test drives the use point (the tool response) and
    asserts the install command in the message came from the helper.
    """

    def test_browser_missing_response_carries_the_helper_string(self, monkeypatch):
        """Force ``_browser_deps_available`` to False and read what the
        RuntimeError says when stealthy fetch tries to launch. W6.1: the
        hint rides the error at the use point, not a startup log."""
        from dhole_mcp import server as srv

        monkeypatch.setattr(srv, "_browser_deps_available", lambda: False)
        # install.browser_install_advice imports the server module's
        # _browser_deps_available; with it returning False the advice must
        # fall through to the install branch.
        msg = install.browser_install_advice()
        assert install.full_install_command() in msg
        assert "playwright install chromium" in msg

    def test_ocr_missing_response_carries_the_helper_string(self, monkeypatch):
        """pdf_extractor.ocr_advice is the pre-W6 reference implementation;
        after W6 it delegates to install.full_install_command, and the
        string in the "not installed" branch is exactly the helper's."""
        from dhole_mcp import ocr

        monkeypatch.setattr(ocr, "ocr_available", lambda: False)
        msg = install.ocr_install_advice()
        assert install.full_install_command() in msg

    def test_docx_missing_parse_response_carries_the_helper_string(
            self, monkeypatch, tmp_path):
        """parse() with a .docx file on a machine without python-docx must
        produce an error whose copy comes from the helper. Not a bare
        literal - W7 changing the helper must not require editing parse.py."""
        import builtins

        # Block the docx import so parse hits the ImportError branch.
        real_import = builtins.__import__

        def fake_import(name, *args, **kwargs):
            if name.split(".")[0] == "docx":
                raise ModuleNotFoundError("No module named 'docx'")
            return real_import(name, *args, **kwargs)

        monkeypatch.setattr(builtins, "__import__", fake_import)

        from dhole_mcp import parse

        target = tmp_path / "sample.docx"
        target.write_bytes(b"not a real docx")
        _content, err = parse.parse_file(str(target))[:2]
        assert install.full_install_command() in err, err

    def test_pdf_extractor_ocr_advice_is_a_thin_delegate(self):
        """The ``pdf_extractor.ocr_advice()`` docstring calls itself "the
        single source of truth for every OCR hint"; after W6 that role is
        held by ``install.ocr_install_advice()`` and the old function just
        wraps it. Asserting no drift is what keeps four call-sites that
        quote it from quietly disagreeing about the same machine."""
        from dhole_mcp import ocr, pdf_extractor

        # Force the "not installed" branch; the wording must be the helper's.
        original = ocr.ocr_available
        try:
            ocr.ocr_available = lambda: False
            text = pdf_extractor.ocr_advice()
            assert install.full_install_command() in text
        finally:
            ocr.ocr_available = original
